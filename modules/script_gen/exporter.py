@dataclass(frozen=True)
class DeliverableArtifact:
    """Metadata for a generated output artifact with integrity checksum."""
    filename: str
    filepath: str
    size_bytes: int
    sha256: str
    created_at: str

    def to_dict(self) -> Dict[str, Any]:
        return {
            "filename": self.filename,
            "filepath": self.filepath,
            "size_bytes": self.size_bytes,
            "sha256": self.sha256,
            "created_at": self.created_at,
        }


# ---------------------------------------------------------------------------
# Utility helpers
# ---------------------------------------------------------------------------


def _sha256_file(path: str) -> str:
    """Compute SHA-256 hex digest of a file."""
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _ensure_output_dir() -> Path:
    """Create ./output/ if it does not exist and return its Path."""
    _OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    return _OUTPUT_DIR


def _deduplicate_imports(snippets: List[str]) -> Tuple[List[str], List[str]]:
    """
    Extracts and deduplicates all import lines from code snippets.

    Returns
    -------
    (unique_import_lines, body_lines_per_snippet)
    """
    seen: set = set()
    import_lines: List[str] = []
    body_blocks: List[str] = []

    for snippet in snippets:
        body_parts: List[str] = []
        for line in snippet.splitlines():
            stripped = line.strip()
            if stripped.startswith("import ") or stripped.startswith("from "):
                if stripped not in seen:
                    seen.add(stripped)
                    import_lines.append(stripped)
            else:
                body_parts.append(line)
        body_blocks.append("\n".join(body_parts).strip())

    return import_lines, body_blocks


