class PipelineScriptGenerator:
    """
    Compiles TransformationAction objects into a self-contained pipeline.py.
    """

    SCRIPT_HEADER = '''"""
AutoData-Hub — Auto-Generated Cleaning Pipeline
Generated by: AutoData-Hub Script Generator (Module 5)
Generated at: {timestamp}
Dataset: {dataset_name}
Version chain: {version_chain}

This script is a standalone, executable Python cleaning pipeline.
Run: python pipeline.py
"""

'''

    def generate(
        self,
        actions: List[TransformationAction],
        dataset_name: str = "dataset",
        version_chain: Optional[List[str]] = None,
        input_csv_path: str = "input.csv",
        output_csv_path: str = "output/cleaned_dataset.csv",
        validate_snippets: bool = True,
    ) -> str:
        """
        Compiles all TransformationActions into a pipeline.py source string.

        Parameters
        ----------
        actions : List[TransformationAction]
            Ordered action ledger from the full pipeline run.
        dataset_name : str
            Display name for the dataset.
        version_chain : Optional[List[str]]
            List of version tags in order, e.g. ['v0_raw', 'v1_privacy', 'v2_imputed', 'v3_anomaly'].
        input_csv_path : str
            Relative path to input CSV for the generated script.
        output_csv_path : str
            Relative path to output CSV for the generated script.
        validate_snippets : bool
            If True, runs each code snippet through the AST sandbox before inclusion.

        Returns
        -------
        str : Complete Python source code of the pipeline script.
        """
        ts = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
        chain_str = " → ".join(version_chain or ["v0_raw", "v1_privacy", "v2_imputed", "v3_anomaly"])

        # Sort actions by step_id for deterministic ordering
        sorted_actions = sorted(actions, key=lambda a: a.step_id)

        # Collect valid snippets, grouped by module
        module_sections: Dict[str, List[Tuple[int, str, str]]] = {}
        for action in sorted_actions:
            snippet = action.code_snippet.strip()
            if not snippet:
                continue

            if validate_snippets:
                try:
                    validate_code(snippet, raise_on_first=True)
                except (ASTSandboxError, SyntaxError) as exc:
                    raise ASTSandboxError(
                        f"Step {action.step_id} ({action.module}/{action.action_type}) "
                        f"failed secure pipeline validation: {exc}"
                    ) from exc

            module = action.module
            if module not in module_sections:
                module_sections[module] = []
            module_sections[module].append((action.step_id, action.action_type, snippet))

        # Collect all snippets for import deduplication
        all_snippets = [s for sections in module_sections.values() for _, _, s in sections]
        import_lines, body_blocks = _deduplicate_imports(all_snippets)

        # Build script lines
        lines: List[str] = []

        # Header
        lines.append(
            self.SCRIPT_HEADER.format(
                timestamp=ts,
                dataset_name=dataset_name,
                version_chain=chain_str,
            )
        )

        # Consolidated imports block
        lines.append("# ── IMPORTS ─────────────────────────────────────────────────────")
        lines.append("import pandas as pd")
        lines.append("import numpy as np")
        for imp in import_lines:
            if imp not in ("import pandas as pd", "import numpy as np"):
                lines.append(imp)
        lines.append("")
        lines.append("")

        # Data loading block
        lines.append("# ── DATA LOADING ─────────────────────────────────────────────────")
        lines.append(f"df = pd.read_csv({input_csv_path!r})")
        lines.append(f'print(f"Loaded dataset: {{df.shape[0]}} rows x {{df.shape[1]}} columns")')
        lines.append("")
        lines.append("")

        # Per-module transformation sections
        module_display = {
            "health_audit": "MODULE 1 — DATA HEALTH AUDIT",
            "privacy": "MODULE 4 — PRIVACY & PII FIREWALL",
            "imputation": "MODULE 2 — MISSING VALUE IMPUTATION",
            "anomaly": "MODULE 3 — ENSEMBLE ANOMALY DETECTION",
        }

        # Flatten body blocks back per module
        module_body_idx = 0
        for module, section_entries in module_sections.items():
            display = module_display.get(module, f"MODULE — {module.upper()}")
            lines.append(f"# ── {display} {'─' * max(0, 65 - len(display))}")

            for step_id, action_type, snippet in section_entries:
                lines.append(f"# Step {step_id}: {action_type.replace('_', ' ').title()}")
                # Use deduplicated body (no repeated imports)
                _, body_blocks_local = _deduplicate_imports([snippet])
                body = body_blocks_local[0].strip()
                if body:
                    lines.append(body)
                lines.append("")

            lines.append("")

        # Save output
        lines.append("# ── OUTPUT ───────────────────────────────────────────────────────")
        lines.append(f"df.to_csv({output_csv_path!r}, index=False)")
        lines.append(f'print(f"Cleaned dataset saved to: {output_csv_path}")')
        lines.append(f'print(f"Final shape: {{df.shape[0]}} rows x {{df.shape[1]}} columns")')
        lines.append("")

        return "\n".join(lines)

    def write(
        self,
        actions: List[TransformationAction],
        dataset_name: str = "dataset",
        version_chain: Optional[List[str]] = None,
        input_csv_path: str = "input.csv",
        output_dir: Optional[Union[str, Path]] = None,
        validate_snippets: bool = True,
        output_path: Optional[Union[str, Path]] = None,
    ) -> DeliverableArtifact:
        """
        Generates and writes pipeline.py to the output directory.

        Returns
        -------
        DeliverableArtifact with SHA-256 checksum.
        """
        if output_path is not None:
            out_path = Path(output_path)
            out_dir = out_path.parent
        else:
            out_dir = Path(output_dir) if output_dir else _ensure_output_dir()
            out_path = out_dir / "pipeline.py"

        out_dir.mkdir(parents=True, exist_ok=True)

        script_src = self.generate(
            actions=actions,
            dataset_name=dataset_name,
            version_chain=version_chain,
            input_csv_path=input_csv_path,
            output_csv_path="cleaned_dataset.csv",
            validate_snippets=validate_snippets,
        )

        with open(out_path, "w", encoding="utf-8") as f:
            f.write(script_src)

        size = out_path.stat().st_size
        sha = _sha256_file(str(out_path))
        ts = datetime.datetime.now(datetime.timezone.utc).isoformat()

        return DeliverableArtifact(
            filename=out_path.name,
            filepath=str(out_path),
            size_bytes=size,
            sha256=sha,
            created_at=ts,
        )


