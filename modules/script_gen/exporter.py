        story.append(Paragraph("3. Per-Module Metric Details", h2_style))
        story.append(HRFlowable(width="100%", thickness=0.5, color=rule_color))

        for mr in module_results:
            story.append(Spacer(1, 0.3 * cm))
            module_title = mr.module_name.replace("_", " ").title()
            story.append(Paragraph(f"Module: {module_title} ({mr.status.value.upper()})", h2_style))

            if mr.metrics:
                metric_rows = [[
                    _cell("Metric", table_header_style),
                    _cell("Value", table_header_style),
                ]]
                excluded_metric_keys = {
                    "columns",
                    "sample_values",
                    "sample_matches",
                }
                for key, val in mr.metrics.items():
                    if str(key).lower() in excluded_metric_keys:
                        continue
                    if isinstance(val, dict):
                        for sub_key, sub_val in val.items():
                            if str(sub_key).lower() in excluded_metric_keys:
                                continue
                            metric_rows.append([
                                _cell(f"{key}.{sub_key}"),
                                _cell(str(sub_val)[:160]),
                            ])
                    elif isinstance(val, (list, tuple)):
                        metric_rows.append([_cell(key), _cell(str(val)[:160])])
                    else:
                        metric_rows.append([_cell(key), _cell(str(val))])

                metric_table = Table(
                    metric_rows,
                    colWidths=[7 * cm, 8.7 * cm],
                    repeatRows=1,
                )
                metric_table.setStyle(_table_style())
                story.append(metric_table)

            if mr.issues:
                story.append(Spacer(1, 0.2 * cm))
                story.append(Paragraph("Issues:", body_style))
                for issue in mr.issues:
                    story.append(Paragraph(f"- {xml_escape(str(issue)[:200])}", mono_style))

        story.append(PageBreak())

        # ── AUDIT TRAIL LOG ──────────────────────────────────────────────────
        story.append(Paragraph("4. Full Audit Trail Log", h2_style))
        story.append(HRFlowable(width="100%", thickness=0.5, color=rule_color))
        story.append(Spacer(1, 0.2 * cm))

        combined_logs = audit_logs or []
        if combined_logs:
            for i, entry in enumerate(combined_logs[:500]):  # cap at 500 lines
                truncated = xml_escape(str(entry)[:200])
                story.append(Paragraph(truncated, mono_style))
            if len(combined_logs) > 500:
                story.append(Paragraph(
                    f"... {len(combined_logs) - 500} additional log entries truncated.", caption_style
                ))
        else:
            story.append(Paragraph("No audit log entries recorded.", body_style))

        story.append(Spacer(1, 0.6 * cm))

        # ── INTEGRITY CHECKSUMS PLACEHOLDER ─────────────────────────────────
        story.append(Paragraph("5. Artifact Integrity", h2_style))
        story.append(HRFlowable(width="100%", thickness=0.5, color=rule_color))
        story.append(Spacer(1, 0.2 * cm))
        story.append(Paragraph(
            "SHA-256 checksums are recorded after artifact generation and stored "
            "alongside each deliverable in the output/ directory.",
            body_style,
        ))

        # ── BUILD PDF ────────────────────────────────────────────────────────
        def _draw_page_footer(canvas, document) -> None:
            canvas.saveState()
            page_width, _ = A4
            footer_y = 1.15 * cm
            canvas.setStrokeColor(colors.HexColor("#CBD5E1"))
            canvas.setLineWidth(0.5)
            canvas.line(document.leftMargin, footer_y + 0.3 * cm,
                        page_width - document.rightMargin, footer_y + 0.3 * cm)
            canvas.setFillColor(colors.HexColor("#334155"))
            canvas.setFont("Helvetica", 7.5)
            canvas.drawString(document.leftMargin, footer_y, "AutoData-Hub | Audit Report")
            canvas.drawRightString(
                page_width - document.rightMargin,
                footer_y,
                f"Page {document.page}",
            )
            canvas.restoreState()

        doc.build(
            story,
            onFirstPage=_draw_page_footer,
            onLaterPages=_draw_page_footer,
        )

        size = out_path.stat().st_size
        sha = _sha256_file(str(out_path))
        created_ts = datetime.datetime.now(datetime.timezone.utc).isoformat()

        return DeliverableArtifact(
            filename="audit_report.pdf",
            filepath=str(out_path),
            size_bytes=size,
            sha256=sha,
            created_at=created_ts,
        )


