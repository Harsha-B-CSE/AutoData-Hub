def export_pipeline_script(
    actions: List[Any],
    dataset_name: str = "dataset",
    version_chain: Optional[List[str]] = None,
    input_csv_path: str = "input.csv",
    output_dir: Optional[Union[str, Path]] = None,
    output_path: Optional[Union[str, Path]] = None,
    validate_snippets: bool = True,
) -> DeliverableArtifact:
    """
    Generates and saves the standalone pipeline.py cleaning script.

    Parameters
    ----------
    actions : List[TransformationAction]
        Ordered ledger of transformation actions from the full pipeline.
    dataset_name : str
        Display name for the dataset (used in script header).
    version_chain : Optional[List[str]]
        Dataset version progression labels.
    input_csv_path : str
        Path to input CSV embedded in the generated script.
    output_dir : Optional[Union[str, Path]]
        Directory to save the pipeline script. Defaults to DatasetManager().get_output_dir().
    output_path : Optional[Union[str, Path]]
        Specific path for the pipeline script (overrides output_dir).
    validate_snippets : bool
        Run AST security sandbox validation on each snippet before inclusion.

    Returns
    -------
    DeliverableArtifact : Metadata including filepath and SHA-256 checksum.
    """
    # Standardize target output path
    if output_path is not None:
        target_file = Path(output_path)
        target_dir = target_file.parent
    else:
        target_dir = Path(output_dir) if output_dir else DatasetManager().get_output_dir()
        target_file = target_dir / "pipeline.py"

    target_dir.mkdir(parents=True, exist_ok=True)

    # Generate code string from actions and write to target_file
    return PipelineScriptGenerator().write(
        actions=actions,
        dataset_name=dataset_name,
        version_chain=version_chain,
        input_csv_path=input_csv_path,
        output_path=target_file,
        validate_snippets=validate_snippets,
    )


