        meta_table.setStyle(_key_value_table_style())
        story.append(meta_table)
        story.append(Spacer(1, 0.6 * cm))

        # ── MODULE EXECUTION SUMMARY ─────────────────────────────────────────
        story.append(Paragraph("1. Module Execution Summary", h2_style))
        story.append(HRFlowable(width="100%", thickness=0.5, color=rule_color))
        story.append(Spacer(1, 0.2 * cm))

        summary_header = ["Module", "Status", "Version", "Key Metric", "Issues"]
        summary_rows = [[_cell(value, table_header_style) for value in summary_header]]

        for mr in module_results:
            # Pick the most informative single key metric
            key_metric = "-"
            metrics = mr.metrics or {}
