"""Phase-coherent harmonic bandwidth extension for narrow-band speech."""

from __future__ import annotations

from contextlib import nullcontext
from functools import lru_cache
import os
from pathlib import Path
import time
from typing import Any, Dict

import numpy as np
from scipy.signal import istft, stft

from modules.voice.audio_loader import downmix_to_mono, resample_audio
from modules.voice.device_manager import resolve_execution_device


def apply_high_freq_reconstruction(
    audio_signal: np.ndarray,
    sr_in: int = 16_000,
    target_sr: int = 48_000,
) -> np.ndarray:
    """Upsample audio and synthesize decaying, phase-aligned upper harmonics.

    The original baseband is retained.  Frequencies above the source Nyquist
    are generated by mapping second and third harmonics from valid source bins,
    with a smooth crossover and conservative energy normalization.
    """

    sr_in = int(sr_in)
    target_sr = int(target_sr)
    if sr_in <= 0 or target_sr <= 0:
        raise ValueError("Sample rates must be positive integers.")
    audio = downmix_to_mono(audio_signal)
    if target_sr <= sr_in or audio.size == 0:
        return resample_audio(audio, sr_in, target_sr)

    upsampled = resample_audio(audio, sr_in, target_sr)
    if upsampled.size < 64 or not np.any(upsampled):
        return upsampled

    nperseg = min(2_048, max(64, 2 ** int(np.floor(np.log2(upsampled.size)))))
    noverlap = min((3 * nperseg) // 4, nperseg - 1)
    frequencies, _, spectrum = stft(
        upsampled,
        fs=target_sr,
        window="hann",
        nperseg=nperseg,
        noverlap=noverlap,
        boundary="zeros",
        padded=True,
    )
    reconstructed = spectrum.copy()
    source_nyquist = sr_in / 2.0
    crossover_start = source_nyquist * 0.90
    high_indices = np.flatnonzero(frequencies > crossover_start)
    if high_indices.size:
        high_frequencies = frequencies[high_indices]
        harmonic_order = np.where(high_frequencies <= 2.0 * source_nyquist, 2, 3)
        source_frequencies = high_frequencies / harmonic_order
        source_indices = np.searchsorted(frequencies, source_frequencies)
        source_indices = np.clip(source_indices, 0, len(frequencies) - 1)
        source_bins = spectrum[source_indices, :]

        source_magnitude = np.abs(source_bins)
        source_phase = np.angle(source_bins)
        phase_aligned = source_magnitude * np.exp(
            1j * source_phase * harmonic_order[:, np.newaxis]
        )
        crossover = np.clip(
            (high_frequencies - crossover_start)
            / max(source_nyquist - crossover_start, 1.0),
            0.0,
            1.0,
        )
        spectral_decay = np.exp(
            -1.7
            * np.maximum(high_frequencies - source_nyquist, 0.0)
            / max(source_nyquist, 1.0)
        )
        harmonic_gain = 0.16 / harmonic_order
        weight = crossover * spectral_decay * harmonic_gain
        generated = phase_aligned * weight[:, np.newaxis]

        # Retain any native upper-band content and only fill its missing energy.
        existing = reconstructed[high_indices, :]
        missing_ratio = np.clip(
            1.0 - np.abs(existing) / (np.abs(generated) + 1e-9), 0.0, 1.0
        )
        reconstructed[high_indices, :] = existing + generated * missing_ratio

    _, extended = istft(
        reconstructed,
        fs=target_sr,
        window="hann",
        nperseg=nperseg,
        noverlap=noverlap,
        input_onesided=True,
        boundary=True,
    )
    extended = np.asarray(extended[: upsampled.size], dtype=np.float32)
    if extended.size < upsampled.size:
        extended = np.pad(extended, (0, upsampled.size - extended.size))

    source_rms = float(np.sqrt(np.mean(np.square(upsampled, dtype=np.float64))))
    result_rms = float(np.sqrt(np.mean(np.square(extended, dtype=np.float64))))
    maximum_rms = source_rms * 1.15
    if result_rms > maximum_rms > 0:
        extended *= maximum_rms / result_rms
    return extended.astype(np.float32, copy=False)


def _resolve_bandwidth_model(device_ctx: dict[str, Any]) -> Path | None:
    explicit = device_ctx.get("bandwidth_model_path") or os.getenv(
        "AUTODATA_BANDWIDTH_MODEL"
    )
    if explicit:
        path = Path(str(explicit)).expanduser().resolve()
        return path if path.is_file() else None
    root_value = os.getenv("AUTODATA_VOICE_MODEL_DIR")
    root = (
        Path(root_value).expanduser().resolve()
        if root_value
        else Path(__file__).resolve().parents[2] / "models" / "voice"
    )
    candidates = (
        "mp_senet.onnx",
        "voicefixer.onnx",
        "mp_senet.pt",
        "voicefixer.torchscript",
    )
    return next((root / name for name in candidates if (root / name).is_file()), None)


def get_bandwidth_model_status(device_ctx: dict | None = None) -> Dict[str, Any]:
    context = dict(device_ctx or resolve_execution_device())
    model_path = _resolve_bandwidth_model(context)
    return {
        "model_name": "MP-SENet / VoiceFixer",
        "model_path": str(model_path) if model_path else None,
        "weights_available": model_path is not None,
        "runtime_available": bool(
            context.get("onnxruntime_available") or context.get("torch_available")
        ),
        "model_contract": "end_to_end_waveform_16khz_to_48khz_v1",
        "ready": model_path is not None
        and bool(context.get("onnxruntime_available") or context.get("torch_available")),
    }


def _normalize_model_output(output: Any, expected_samples: int) -> np.ndarray:
    if isinstance(output, dict):
        output = next(iter(output.values()))
    if isinstance(output, (tuple, list)):
        output = output[0]
    if hasattr(output, "detach"):
        output = output.detach().float().cpu().numpy()
    audio = np.squeeze(np.asarray(output))
    if np.iscomplexobj(audio) or audio.ndim != 1 or audio.size == 0:
        raise ValueError("Bandwidth model output is not a decoded mono waveform.")
    audio = audio.astype(np.float32, copy=False)
    if audio.size != expected_samples:
        raise ValueError(
            f"Bandwidth model output length {audio.size} does not match the "
            f"required {expected_samples} samples."
        )
    if not np.all(np.isfinite(audio)):
        raise ValueError("Bandwidth model output contains non-finite audio samples.")
    peak = float(np.max(np.abs(audio)))
    if peak > 1.05:
        audio /= peak
    return np.clip(audio, -1.0, 1.0)


@lru_cache(maxsize=4)
def _load_bandwidth_onnx(
    model_path: str,
    providers: tuple[str, ...],
    modified_ns: int,
):
    del modified_ns
    import onnxruntime as ort  # type: ignore

    options = ort.SessionOptions()
    options.intra_op_num_threads = 1
    options.inter_op_num_threads = 1
    return ort.InferenceSession(
        model_path, sess_options=options, providers=list(providers)
    )


def _run_bandwidth_onnx(
    model_path: Path,
    audio: np.ndarray,
    expected_samples: int,
    device_ctx: dict[str, Any],
) -> np.ndarray:
    providers = tuple(device_ctx.get("providers") or ["CPUExecutionProvider"])
    session = _load_bandwidth_onnx(
        str(model_path), providers, model_path.stat().st_mtime_ns
    )
    inputs = session.get_inputs()
    if len(inputs) != 1:
        raise ValueError("The bandwidth ONNX wrapper must expose one waveform input.")
    rank = len(getattr(inputs[0], "shape", []) or [])
    input_type = str(getattr(inputs[0], "type", "tensor(float)"))
    if "float" not in input_type:
        raise ValueError("The bandwidth ONNX input must be floating point.")
    if rank in (0, 1):
        shaped = audio
    elif rank == 2:
        shaped = audio[np.newaxis, :]
    elif rank == 3:
        shaped = audio[np.newaxis, np.newaxis, :]
    else:
        raise ValueError("The bandwidth ONNX input must have rank 1-3.")
    outputs = session.run(
        None, {inputs[0].name: np.ascontiguousarray(shaped, dtype=np.float32)}
    )
    if not outputs:
        raise ValueError("Bandwidth ONNX model produced no output.")
    return _normalize_model_output(outputs[0], expected_samples)


@lru_cache(maxsize=4)
def _load_bandwidth_torchscript(
    model_path: str,
    device: str,
    modified_ns: int,
):
    del modified_ns
    import torch  # type: ignore

    model = torch.jit.load(model_path, map_location=device)
    model.eval()
    return model


def _run_bandwidth_torchscript(
    model_path: Path,
    audio: np.ndarray,
    expected_samples: int,
    device_ctx: dict[str, Any],
) -> np.ndarray:
    import torch  # type: ignore

    device = str(device_ctx.get("pytorch_device", device_ctx.get("device", "cpu")))
    model = _load_bandwidth_torchscript(
        str(model_path), device, model_path.stat().st_mtime_ns
    )
    tensor = torch.from_numpy(audio).to(device).reshape(1, 1, -1)
    factory = device_ctx.get("autocast_context")
    autocast = factory() if callable(factory) else nullcontext()
    with torch.no_grad(), autocast:
        output = model(tensor)
    return _normalize_model_output(output, expected_samples)


def apply_voicefixer_sota(
    audio_signal: np.ndarray,
    sr_in: int = 16_000,
    target_sr: int = 48_000,
    device_ctx: dict | None = None,
) -> Dict[str, Any]:
    """Run an optional MP-SENet/VoiceFixer wrapper with harmonic fallback."""

    started = time.perf_counter()
    context = dict(device_ctx or resolve_execution_device())
    audio = downmix_to_mono(audio_signal)
    expected_samples = max(1, int(round(audio.size * int(target_sr) / int(sr_in))))
    model_path = _resolve_bandwidth_model(context)
    enhanced = None
    runtime = None
    fallback_reason = None
    if model_path is None:
        fallback_reason = "weights_missing"
    elif model_path.suffix.lower() == ".onnx":
        if not context.get("onnxruntime_available"):
            fallback_reason = "onnxruntime_unavailable"
        else:
            try:
                enhanced = _run_bandwidth_onnx(
                    model_path, audio, expected_samples, context
                )
                runtime = "onnxruntime"
            except ValueError:
                fallback_reason = "incompatible_model_contract"
            except Exception as exc:
                fallback_reason = f"inference_error:{type(exc).__name__}"
    else:
        if not context.get("torch_available"):
            fallback_reason = "pytorch_unavailable"
        else:
            try:
                enhanced = _run_bandwidth_torchscript(
                    model_path, audio, expected_samples, context
                )
                runtime = "pytorch"
            except ValueError:
                fallback_reason = "incompatible_model_contract"
            except Exception as exc:
                fallback_reason = f"inference_error:{type(exc).__name__}"

    if enhanced is None:
        enhanced = apply_high_freq_reconstruction(audio, sr_in, target_sr)
        runtime = "phase_aligned_harmonic_extension"
        status = "fallback"
    else:
        status = "success"
    result: Dict[str, Any] = {
        "audio": enhanced,
        "enhanced_audio": enhanced,
        "sample_rate": int(target_sr),
        "status": status,
        "model": "MP-SENet / VoiceFixer",
        "model_contract": "end_to_end_waveform_16khz_to_48khz_v1",
        "model_path": str(model_path) if model_path else None,
        "runtime": runtime,
        "execution_provider": context.get("execution_provider", "unavailable"),
        "elapsed_ms": (time.perf_counter() - started) * 1_000.0,
    }
    if fallback_reason:
        result["fallback_reason"] = fallback_reason
    return result
